/** Presets are sparse upstream records; every load must begin from fresh defaults. */
export function createSettings(presetId = DEFAULT_PRESET_ID) {
  const preset = PRESETS.find((item) => item.id === presetId);
  if (!preset) throw new RangeError(`Unknown Mesh Grid preset: ${presetId}`);
  return structuredClone({
    ...GLOBAL_DEFAULTS,
    ...MESH_DEFAULTS,
    ...EFFECT_DEFAULTS,
    effectOrder: [...EFFECT_ORDER],
    ...preset.data,
  });
}
